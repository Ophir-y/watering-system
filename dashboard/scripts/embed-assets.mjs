// Compiles dist/ into firmware/src/generated/web_assets.h: one gzipped byte array per
// file plus a lookup table (see firmware/src/net/WebAssets.h).
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative } from 'node:path';
import { gzipSync } from 'node:zlib';

const dist = new URL('../dist/', import.meta.url).pathname;
const out = new URL('../../firmware/src/generated/web_assets.h', import.meta.url).pathname;

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.json': 'application/json',
  '.woff2': 'font/woff2',
  '.woff': 'font/woff',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.txt': 'text/plain; charset=utf-8',
  '.webmanifest': 'application/manifest+json',
};

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = walk(dist).sort();
let body = '';
const table = [];
let total = 0;

files.forEach((file, i) => {
  const raw = readFileSync(file);
  const gz = gzipSync(raw, { level: 9 });
  const useGzip = gz.length < raw.length;
  const data = useGzip ? gz : raw;
  const path = '/' + relative(dist, file).split('\\').join('/');
  const type = TYPES[extname(file).toLowerCase()] ?? 'application/octet-stream';
  const etag = `"${createHash('sha1').update(raw).digest('hex').slice(0, 16)}"`;
  const immutable = path.startsWith('/assets/');
  total += data.length;

  const hex = [];
  for (let j = 0; j < data.length; j++) hex.push(`0x${data[j].toString(16).padStart(2, '0')}`);
  const lines = [];
  for (let j = 0; j < hex.length; j += 16) lines.push('  ' + hex.slice(j, j + 16).join(', '));
  body += `// ${path} (${raw.length} bytes${useGzip ? `, ${data.length} gzipped` : ''})\n`;
  body += `static const uint8_t kAsset${i}[] = {\n${lines.join(',\n')}\n};\n\n`;
  table.push(
    `  {${JSON.stringify(path)}, ${JSON.stringify(type)}, kAsset${i}, sizeof(kAsset${i}), ${JSON.stringify(etag)}, ${useGzip}, ${immutable}},`,
  );
});

const header = `// AUTO-GENERATED by dashboard/scripts/embed-assets.mjs from dashboard/dist. Do not edit.
// ${files.length} files, ${total} bytes.
#pragma once

#include <stddef.h>
#include <stdint.h>

${body}static const WebAsset kWebAssets[] = {
${table.join('\n')}
};
static const size_t kWebAssetCount = ${files.length};
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, header);
console.log(
  `Embedded ${files.length} files (${(total / 1024).toFixed(1)} KB) into ${relative(process.cwd(), out)}`,
);
